package com.pengcheng.phoenixgraph.integration.sanguo;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Turns the parsed {@link SanguoDataset} into the frozen RDF artifacts of the
 * knowledge graph:
 *
 * <ul>
 *   <li>{@code sanguo-ontology.ttl} — the entity / relation split (TBox);</li>
 *   <li>{@code sanguo-kg.ttl} — the instance graph (ABox), readable Turtle;</li>
 *   <li>{@code sanguo-kg.nt} — the same graph as N-Triples, the machine form;</li>
 *   <li>{@code VALIDATION.md} — the {@link SanguoRdfValidator} report.</li>
 * </ul>
 *
 * <p>Run it against the plain (uncompressed) dataset files:
 *
 * <pre>{@code
 * java -cp graph-integration-test/target/test-classes:... \
 *      com.pengcheng.phoenixgraph.integration.sanguo.SanguoRdfGenerator \
 *      .datasets/sanguo target/sanguo-rdf
 * }</pre>
 *
 * <p>{@code SanguoRdfTest} calls the same code and asserts the result equals the
 * artifacts committed under {@code src/test/resources/kg/sanguo/rdf/}, so the
 * files cannot drift away from the parser.
 */
public final class SanguoRdfGenerator {

    /** The four artifacts, as strings. */
    public record Artifacts(String ontologyTurtle, String instanceTurtle, String instanceNTriples,
                            String validationReport) {
    }

    private SanguoRdfGenerator() {
    }

    /** Builds the artifacts in memory. */
    public static Artifacts generate(SanguoDataset dataset) {
        List<SanguoRdf.Triple> tbox = SanguoRdf.ontologyTriples(dataset.ontology());
        List<SanguoRdf.Triple> abox = SanguoRdf.instanceTriples(dataset);

        String ontology = header("三国演义知识图谱 — 本体 (TBox)",
                "The entity / relation split: classes and the 64 object properties of the\n"
                        + "OpenKG 四大名著 ontology (三国演义 part), re-homed into the PhoenixGraph\n"
                        + "knowledge-graph namespace, plus the four document-derived properties.")
                + "\n" + SanguoRdf.toTurtle(tbox);

        String graph = header("三国演义知识图谱 — 实例数据 (ABox)",
                "Parsed from renwu_process_v1.csv (331 person documents), triples.csv (153 curated\n"
                        + "relation triples) and the local supplement triples-extra.csv (8 triples: the\n"
                        + "五虎上将 offices and the 关羽/张飞 臣属 edges, see SANGUO-KG-QUERIES.md §9);\n"
                        + "the ontology's inverse and symmetric rules are materialized. Entities: Male,\n"
                        + "Female, Person (relation-only), Faction, Place, Position and Chapter.")
                + "\n" + SanguoRdf.toTurtle(abox);

        String ntriples = header("三国演义知识图谱 — N-Triples", null) + "\n" + SanguoRdf.toNTriples(abox);

        return new Artifacts(ontology, graph, ntriples, report(dataset));
    }

    /** Writes the artifacts into a directory. */
    public static Artifacts write(SanguoDataset dataset, Path directory) {
        Artifacts artifacts = generate(dataset);
        SanguoRdf.write(directory.resolve("sanguo-ontology.ttl"), artifacts.ontologyTurtle());
        SanguoRdf.write(directory.resolve("sanguo-kg.ttl"), artifacts.instanceTurtle());
        SanguoRdf.write(directory.resolve("sanguo-kg.nt"), artifacts.instanceNTriples());
        SanguoRdf.write(directory.resolve("VALIDATION.md"), artifacts.validationReport());
        return artifacts;
    }

    /** A Markdown report of the parse and its validation. */
    public static String report(SanguoDataset dataset) {
        SanguoRdfValidator.Report report = SanguoRdfValidator.validate(dataset);
        List<SanguoRdf.Triple> abox = SanguoRdf.instanceTriples(dataset);
        List<SanguoRdf.Triple> tbox = SanguoRdf.ontologyTriples(dataset.ontology());

        StringBuilder out = new StringBuilder();
        out.append("# 《三国演义》knowledge graph — RDF validation\n\n");
        out.append("Generated by `SanguoRdfGenerator` from `renwu_process_v1.csv`, `triples.csv` and `theory.owl`.\n\n");
        out.append("## Result\n\n");
        out.append(report.valid()
                ? "**PASS** — the parse satisfies every rule of the ontology.\n\n"
                : "**FAIL** — " + report.violations().size() + " violation(s).\n\n");

        out.append("## Shape\n\n");
        out.append("| | |\n|---|---|\n");
        out.append("| person documents | ").append(dataset.documents().size()).append(" |\n");
        out.append("| entities (ABox) | ").append(report.entityCount()).append(" |\n");
        out.append("| parsed relations | ").append(report.relationCount()).append(" |\n");
        out.append("| materialized relations (inverse + symmetric closure) | ").append(report.closedRelationCount()).append(" |\n");
        out.append("| curated triples in the file | ").append(report.curatedCount()).append(" |\n");
        out.append("| local supplement triples ({@code triples-extra.csv}) | ").append(report.extraCount()).append(" |\n");
        out.append("| duplicate curated triples (collapsed) | ").append(report.duplicateCurated()).append(" |\n");
        out.append("| ontology statements (TBox) | ").append(tbox.size()).append(" |\n");
        out.append("| RDF triples (ABox) | ").append(abox.size()).append(" |\n\n");

        out.append("### Entities by type\n\n| type | n |\n|---|---|\n");
        Map<String, Integer> byType = new java.util.TreeMap<>();
        for (SanguoDataset.Entity entity : dataset.entities().values()) {
            byType.merge(entity.type().rdfClass(), 1, Integer::sum);
        }
        byType.forEach((type, n) -> out.append("| ").append(type).append(" | ").append(n).append(" |\n"));

        out.append("\n### Relations by family\n\n| family | n |\n|---|---|\n");
        report.relationFamilyUsage().forEach((family, n) ->
                out.append("| ").append(family).append(" | ").append(n).append(" |\n"));

        out.append("\n### Relations by name\n\n| relation | 中文 | n |\n|---|---|---|\n");
        report.relationUsage().forEach((relation, n) -> out.append("| `").append(relation).append("` | ")
                .append(dataset.ontology().label(relation)).append(" | ").append(n).append(" |\n"));

        out.append("\n## Checks\n\n| rule | result |\n|---|---|\n");
        out.append("| declared predicate | ")
                .append(report.violations("declared").isEmpty() ? "ok — every predicate is in the TBox" : "FAILED").append(" |\n");
        out.append("| no dangling IRI | ")
                .append(report.violations("no-dangling").isEmpty() ? "ok — every subject/object is a declared entity" : "FAILED").append(" |\n");
        out.append("| rdfs:domain / rdfs:range | ").append(report.domainRangeChecked())
                .append(" checked, ").append(report.domainRangeUnverifiable())
                .append(" unverifiable (relation-only person), ")
                .append(report.violations("domain").size() + report.violations("range").size())
                .append(" violated |\n");
        out.append("| owl:IrreflexiveProperty | ")
                .append(report.violations("irreflexive").isEmpty() ? "ok — no self loop" : "FAILED").append(" |\n");
        out.append("| owl:AsymmetricProperty | ")
                .append(report.violations("asymmetric").isEmpty() ? "ok — never both directions" : "FAILED").append(" |\n");
        out.append("| owl:inverseOf closure | ")
                .append(report.violations("inverse-closure").isEmpty() ? "ok — every inverse materialized" : "FAILED").append(" |\n");
        out.append("| owl:SymmetricProperty closure | ")
                .append(report.violations("symmetric-closure").isEmpty() ? "ok — every mirror materialized" : "FAILED").append(" |\n");
        out.append("| inverse involution | ")
                .append(report.violations("involution").isEmpty() ? "ok — inverse(inverse(r)) == r" : "FAILED").append(" |\n");

        out.append("\n### Inverse pairs\n\n| relation | 中文 | inverse | 中文 |\n|---|---|---|---|\n");
        dataset.ontology().properties().stream()
                .filter(p -> !dataset.ontology().inverse(p.name()).equals(p.name()))
                .filter(p -> p.name().compareTo(dataset.ontology().inverse(p.name())) < 0)
                .forEach(p -> out.append("| `").append(p.name()).append("` | ").append(p.label())
                        .append(" | `").append(dataset.ontology().inverse(p.name())).append("` | ")
                        .append(dataset.ontology().label(dataset.ontology().inverse(p.name()))).append(" |\n"));

        if (!report.violations().isEmpty()) {
            out.append("\n## Violations\n\n");
            out.append("| rule | subject | relation | object | detail |\n|---|---|---|---|---|\n");
            for (SanguoRdfValidator.Violation violation : report.violations()) {
                out.append("| ").append(violation.rule()).append(" | ").append(violation.subject())
                        .append(" | `").append(violation.relation()).append("` | ").append(violation.object())
                        .append(" | ").append(violation.detail()).append(" |\n");
            }
        }
        return out.toString();
    }

    private static String header(String title, String comment) {
        StringBuilder out = new StringBuilder();
        out.append("# ").append(title).append('\n');
        out.append("#\n");
        if (comment != null) {
            for (String line : comment.split("\n")) {
                out.append("# ").append(line).append('\n');
            }
            out.append("#\n");
        }
        out.append("# Source: OpenKG 四大名著人物关系知识图谱和 OWL 本体 (三国演义 part),\n");
        out.append("#         https://github.com/wcswcswcs/sgyy\n");
        out.append("# Generated by SanguoRdfGenerator — do not edit by hand.\n\n");
        out.append(SanguoRdf.prefixes());
        return out.toString();
    }

    /** Command line: {@code SanguoRdfGenerator <plain-dataset-dir> <out-dir>}. */
    public static void main(String[] args) {
        Path datasetDir = Path.of(args.length > 0 ? args[0] : ".datasets/sanguo");
        Path outDir = Path.of(args.length > 1 ? args[1] : "target/sanguo-rdf");
        SanguoOntology ontology = SanguoOntology.loadFile(datasetDir.resolve("theory.owl"));
        SanguoDataset dataset = SanguoDataset.loadFiles(datasetDir.resolve("renwu_process_v1.csv"),
                datasetDir.resolve("triples.csv"), ontology);
        Artifacts artifacts = write(dataset, outDir);
        SanguoRdfValidator.Report report = SanguoRdfValidator.validate(dataset);
        System.out.printf("[sanguo] %d documents, %d entities, %d relations (+%d closure) -> %s%n",
                dataset.documents().size(), report.entityCount(), report.relationCount(),
                report.closedRelationCount() - report.relationCount(), outDir.toAbsolutePath());
        System.out.printf("[sanguo] TBox %d statements, ABox %d triples, validation %s%n",
                new ArrayList<>(SanguoRdf.ontologyTriples(ontology)).size(),
                new ArrayList<>(SanguoRdf.instanceTriples(dataset)).size(),
                report.valid() ? "PASS" : "FAIL " + report.violations().size());
        if (!report.valid()) {
            report.violations().forEach(v -> System.out.println("  " + v));
        }
    }
}
